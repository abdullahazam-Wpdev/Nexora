import argparse
import json
import math
import time
from dataclasses import asdict
import torch
from torch.nn import functional as F
from tokenizers import Tokenizer, models, trainers, pre_tokenizers, decoders
from safetensors.torch import save_file, load_file
from nexora.config import STORE
from nexora.model import Core, Config
from nexora.datasets import prepare


def write_json(path, value):
    tmp = path.with_suffix(".tmp")
    tmp.write_text(json.dumps(value, indent=2))
    tmp.replace(path)


def _run(steps=160, resume=False):
    torch.set_num_threads(2)
    torch.manual_seed(42)
    run_dir = STORE / "tiny-core"
    if (run_dir / "result.json").exists() and not resume:
        raise ValueError(
            "Legacy run already exists; use nexora.research to create a new experiment"
        )
    run_dir.mkdir(exist_ok=True)
    # Numerical fixtures are programmatically generated, not third-party AI prose.
    texts = [
        f"{i} + {j} = {i + j}. {i} - {j} = {i - j}.\n"
        for i in range(16)
        for j in range(8)
    ]
    manifest = prepare(
        texts,
        approved=True,
        license="CC0-1.0",
        provenance="Local arithmetic fixture generated by deterministic Python code; no external corpus or model outputs.",
    )
    write_json(run_dir / "dataset.json", manifest)
    tokenizer = Tokenizer(models.BPE(unk_token="[UNK]"))
    tokenizer.pre_tokenizer = pre_tokenizers.ByteLevel(add_prefix_space=False)
    tokenizer.decoder = decoders.ByteLevel()
    tokenizer.train_from_iterator(
        manifest["splits"]["train"],
        trainers.BpeTrainer(
            vocab_size=384,
            special_tokens=["[UNK]"],
            initial_alphabet=pre_tokenizers.ByteLevel.alphabet(),
        ),
    )
    if resume:
        tokenizer = Tokenizer.from_file(str(run_dir / "tokenizer.json"))
    else:
        tokenizer.save(str(run_dir / "tokenizer.json"))
    c = Config(vocab_size=tokenizer.get_vocab_size())
    model = Core(c)
    optimizer = torch.optim.AdamW(model.parameters(), lr=0.003, weight_decay=0.01)
    start = 0
    history = []
    if resume:
        state = torch.load(run_dir / "resume.pt", map_location="cpu", weights_only=True)
        if Config(**state["config"]) != c:
            raise ValueError("Checkpoint config mismatch")
        model.load_state_dict(state["model"])
        optimizer.load_state_dict(state["optimizer"])
        torch.set_rng_state(state["rng"])
        start = state["step"]
        history = state["history"]

    def pack(split):
        tokens = tokenizer.encode("\n".join(manifest["splits"][split])).ids
        return torch.tensor(tokens, dtype=torch.long)

    train, val, test = [pack(s) for s in ("train", "validation", "test")]

    def batch(tokens):
        offsets = torch.randint(len(tokens) - c.context - 1, (4,))
        x = torch.stack([tokens[i : i + c.context] for i in offsets])
        y = torch.stack([tokens[i + 1 : i + c.context + 1] for i in offsets])
        return x, y

    def loss(tokens):
        x, y = batch(tokens)
        return F.cross_entropy(model(x).flatten(0, 1), y.flatten())

    begin = time.monotonic()
    for step in range(start, start + steps):
        model.train()
        optimizer.zero_grad()
        lr = (
            0.003
            * min(1, (step + 1) / 10)
            * (0.15 + 0.85 * 0.5 * (1 + math.cos(math.pi * min(step, 500) / 500)))
        )
        for group in optimizer.param_groups:
            group["lr"] = lr
        total = 0
        for _ in range(2):
            l = loss(train) / 2
            l.backward()
            total += l.item()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 1)
        optimizer.step()
        if step % 10 == 0 or step == start + steps - 1:
            model.eval()
            with torch.random.fork_rng(), torch.no_grad():
                vl = loss(val).item()
            history.append(
                {"step": step + 1, "train_loss": total, "validation_loss": vl, "lr": lr}
            )
            print(json.dumps(history[-1]), flush=True)
    model.eval()
    with torch.random.fork_rng(), torch.no_grad():
        test_loss = loss(test).item()
    save_file(model.state_dict(), str(run_dir / "model.safetensors"))
    torch.save(
        {
            "model": model.state_dict(),
            "optimizer": optimizer.state_dict(),
            "rng": torch.get_rng_state(),
            "step": start + steps,
            "history": history,
            "config": asdict(c),
        },
        run_dir / "resume.pt",
    )
    result = {
        "id": "tiny-core",
        "name": "NEXORA Core · arithmetic smoke",
        "status": "completed",
        "steps": start + steps,
        "parameters": sum(p.numel() for p in model.parameters()),
        "config": asdict(c),
        "history": history,
        "test_loss": test_loss,
        "seconds": time.monotonic() - begin,
        "origin": "random initialization; local arithmetic fixtures",
        "warning": "Tiny research model; not a conversational assistant",
        "checkpoint": "model.safetensors",
    }
    write_json(run_dir / "result.json", result)
    return result


def run(steps=160, resume=False):
    """Compatibility smoke runner; new platform jobs use the versioned research engine."""
    from nexora.artifacts import lock

    with lock(STORE / ".training.lock"):
        return _run(steps, resume)


def infer(prompt, count=32):
    folder = STORE / "tiny-core"
    result = json.loads((folder / "result.json").read_text())
    tokenizer = Tokenizer.from_file(str(folder / "tokenizer.json"))
    model = Core(Config(**result["config"]))
    model.load_state_dict(load_file(str(folder / "model.safetensors")))
    ids = tokenizer.encode(prompt).ids or [0]
    output = model.generate(torch.tensor([ids]), count)[0].tolist()
    return {
        "text": tokenizer.decode(output),
        "new_tokens": count,
        "model": "tiny-core",
        "warning": result["warning"],
    }


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--steps", type=int, default=160)
    p.add_argument("--resume", action="store_true")
    a = p.parse_args()
    if not 1 <= a.steps <= 2000:
        p.error("steps must be 1..2000")
    run(a.steps, a.resume)
